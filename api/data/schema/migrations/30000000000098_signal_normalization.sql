CREATE EXTENSION tablefunc;

CREATE VIEW signal_normalization AS (
     SELECT signal_type, AVG(ml_value) AS average, CASE WHEN STDDEV(ml_value) = 0 THEN 1 ELSE STDDEV(ml_value) END AS standard_deviation FROM account_signals
	 WHERE signal_type IN (
		'average deck ban score',
		'banned by human',
	    'base cards owned',
	    'cards unlocked',
	    'cards unlocked - constructed players only',
	    'digits in username',
	    'gold cards owned',
	    'matches average duration',
	    'matches average nonce',
	    'matches played',
	    'matches played conquest',
	    'matches played conquest %',
	    'matches played constructed',
	    'matches played forfeited %',
	    'matches played vs banned %',
	    'matches played vs feeder %',
	    'matches won %',
	    'matches won by forfeit %',
	    'max deck ownership %',
	    'player is feeder',
	    'same ip',
	    'same ip same account date',
	    'silver cards owned',
	    'similar usernames registered close together',
	    'user report count',
	    'user reports per game',
	    'weird username'

	)
	GROUP BY 1
 );

CREATE VIEW normalized_signal_values AS (
	SELECT sig.account_address, sig.signal_type, coalesce((sig.ml_value-norm.average)/norm.standard_deviation, 0) as ml_value FROM account_signals sig  JOIN signal_normalization norm ON norm.signal_type = sig.signal_type
	WHERE sig.signal_type IN (
		'average deck ban score',
        'banned by human',
	    'base cards owned',
	    'cards unlocked',
	    'cards unlocked - constructed players only',
